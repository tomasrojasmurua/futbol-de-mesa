const OCEAN = ['#4589cb', '#3878bd', '#2e69ab', '#295f9f']; // de la costa a mar adentro
const LAND = {
  '#': { base: '#5aae43', lit: '#8bd066', dark: '#3c8530', tex: '#4f9e3b' },
  o: { base: '#8b8c74', lit: '#a7a88f', dark: '#6b6c58', tex: '#82836c' },
};

export function paintMap(cv, key) {
  const rows = MAPS[key];
  cv.width = W; cv.height = H;
  const g = cv.getContext('2d');
  const at = (x, y) => (x < 0 || y < 0 || x >= W || y >= H ? null : rows[y][x]);
  const sea = (c) => c === '.';
  // distancia a la costa para dar el bajo claro y el mar profundo
  const dist = (x, y) => {
    for (let d = 1; d < OCEAN.length; d++) {
      for (let dy = -d; dy <= d; dy++) for (let dx = -d; dx <= d; dx++) { const c = at(x + dx, y + dy); if (c && !sea(c)) return d - 1; }
    }
    return OCEAN.length - 1;
  };
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const c = rows[y][x];
    let col;
    if (sea(c)) {
      const d = dist(x, y);
      col = OCEAN[d];
      // oleaje suave y paralelos punteados en el mar abierto
      if (d >= 2 && (x * 3 + y * 7) % 13 === 0) col = OCEAN[d - 1];
      if (d >= 2 && y % 8 === 4 && x % 2 === 0) col = OCEAN[d - 1];
    } else {
      const p = LAND[c];
      // luz desde arriba a la izquierda: borde claro al norte/oeste y sombra al sur/este
      const n = at(x, y - 1), wv = at(x - 1, y), s = at(x, y + 1), e = at(x + 1, y);
      if ((n && sea(n)) || (wv && sea(wv))) col = p.lit;
      else if ((s && sea(s)) || (e && sea(e))) col = p.dark;
      else col = (x * 7 + y * 13) % 9 === 0 ? p.tex : p.base;
    }
    g.fillStyle = col; g.fillRect(x, y, 1, 1);
  }
  // marco como el de las banderas
  g.fillStyle = 'rgba(0,0,0,.35)'; g.fillRect(0, H - 1, W, 1); g.fillRect(W - 1, 0, 1, H);
  g.fillStyle = 'rgba(255,255,255,.12)'; g.fillRect(0, 0, W, 1); g.fillRect(0, 0, 1, H);
  return cv;
}
